import numpy as np
import matplotlib.pyplot as plt
import matplotlib.animation as animation

def plot_single_run(history):
    fig, ax = plt.subplots()
    ax.plot(history['day'], history['s'], label='Susceptible Population')
    ax.plot(history['day'], history['i'], label='Infected Population')
    ax.plot(history['day'], history['r'], label='Recovered Population')
    ax.set_xlabel("Days")
    ax.set_ylabel("Agents")
    ax.legend()

def plot_mc_uncert(curves_array,n_agents):
    fig, ax = plt.subplots()
    pct = (curves_array/n_agents)*100
    days = np.arange(pct.shape[1])
    for curve in pct:
        ax.plot(days, curve, alpha = 0.05)
    median = np.percentile(pct, 50, axis=0)
    lower = np.percentile(pct, 2.5, axis=0)
    upper = np.percentile(pct, 97.5, axis=0)
    ax.fill_between(days, lower, upper, alpha=0.2, label='95% CI')
    ax.plot(days, median, lw=2.5,label='Median infected %')
    ax.set_xlabel("Day"); ax.set_ylabel("% Population infected")
    ax.set_title("Monte Carlo uncertainty bands", fontweight='bold')
    ax.legend()
    plt.show()
    
def plot_outcome_dist(df):
    fig, axes = plt.subplots(1, 3)
    for ax, (col, label) in zip(axes, [('peak_infected_pct', 'Peak infected (%)'), ('attack_rate_pct', 'Attack rate (%)'), ('peak_day', 'Day of peak')]):
        ax.hist(df[col], bins=25, edgecolor='white', alpha=0.85)
        ax.axvline(df[col].median(), color='black', linestyle='--', label=f'Median: {df[col].median():.1f}')
        ax.set_xlabel(label)
        ax.set_ylabel("Runs")
        ax.set_title(label, fontweight='bold')
        ax.legend()
        
    fig.suptitle("Monte Carlo outcome distributions ")
    plt.show()
    

