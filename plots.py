def animate_epidemic(model_history, agents, grid_size, filename="epidemic.gif"):

    snapshots = model_history.get('snapshots', model_history.get('snapshot', None))
    if snapshots is None:
        print("No snapshots found in history — check model._record()")
        return

    days = model_history['day']
    s_series = model_history['s']
    i_series = model_history['i']
    r_series = model_history['r']
    n_agents = len(agents)
    n_days = len(days)

    fig, (ax_grid, ax_curve) = plt.subplots(1, 2, figsize=(12, 5))
    fig.patch.set_facecolor('#0f172a')
    for ax in [ax_grid, ax_curve]:
        ax.set_facecolor('#1e293b')
        ax.tick_params(colors='white')
        for spine in ax.spines.values():
            spine.set_edgecolor('#334155')

    color = {'s': '#378ADD', 'i': '#E24B4A', 'r': '#4CAF50'}

    # --- Grid setup ---
    ax_grid.set_xlim(-1, grid_size)
    ax_grid.set_ylim(-1, grid_size)
    ax_grid.set_aspect('equal')
    ax_grid.set_xticks([])
    ax_grid.set_yticks([])

    # --- Curve setup ---
    ax_curve.set_xlim(0, n_days)
    ax_curve.set_ylim(0, n_agents * 1.05)
    ax_curve.set_xlabel("Day", color='white')
    ax_curve.set_ylabel("Agents", color='white')

    line_s, = ax_curve.plot([], [], color=color['s'], lw=2, label='Susceptible')
    line_i, = ax_curve.plot([], [], color=color['i'], lw=2, label='Infected')
    line_r, = ax_curve.plot([], [], color=color['r'], lw=2, label='Recovered')
    ax_curve.legend(loc='upper right', fontsize=9,
                    facecolor='#1e293b', labelcolor='white', framealpha=0.8)

    def update(frame):
        # --- Clear and redraw grid every frame ---
        ax_grid.cla()
        ax_grid.set_facecolor('#1e293b')
        ax_grid.set_xlim(-1, grid_size)
        ax_grid.set_ylim(-1, grid_size)
        ax_grid.set_aspect('equal')
        ax_grid.set_xticks([])
        ax_grid.set_yticks([])
        ax_grid.set_title(f"Day {days[frame]}", color='white', fontsize=12)
        for spine in ax_grid.spines.values():
            spine.set_edgecolor('#334155')

        snap = snapshots[frame]
        for key, label in [('s', 'S'), ('i', 'I'), ('r', 'R')]:
            pts = snap[key]
            if pts:
                xs, ys = zip(*pts)
                size = 18 if key == 'i' else 12
                ax_grid.scatter(xs, ys, s=size, c=color[key],
                                alpha=1.0 if key == 'i' else 0.7,
                                label=label)

        ax_grid.legend(loc='upper right', fontsize=9,
                       facecolor='#1e293b', labelcolor='white', framealpha=0.8)

        # --- Update SIR curve ---
        line_s.set_data(days[:frame+1], s_series[:frame+1])
        line_i.set_data(days[:frame+1], i_series[:frame+1])
        line_r.set_data(days[:frame+1], r_series[:frame+1])

    ani = animation.FuncAnimation(
        fig, update, frames=n_days,
        interval=80, blit=False
    )

    print("Saving GIF — this takes a minute...")
    ani.save(filename, writer='pillow', fps=15, dpi=90)
    print(f"Saved: {filename}")
    plt.close()
def plot_evolution(history):
  fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))
  days = history['day']

  # mean infectivity drift
  ax1.plot(days, history['mean_inf'], color='#E24B4A', lw=2)
  ax1.set_xlabel("Day")
  ax1.set_ylabel("Mean infectivity")
  ax1.set_title("Viral evolution — infectivity drift", fontweight='bold')

  # overlay infected count for context
  ax1b = ax1.twinx()
  ax1b.fill_between(days, history['i'], alpha=0.08, color='grey')
  ax1b.set_ylabel("Infected", color='grey', fontsize=9)
  ax1b.tick_params(colors='grey')

  # SIR curve alongside
  ax2.plot(days, history['s'], color='#378ADD', lw=2, label='Susceptible')
  ax2.plot(days, history['i'], color='#E24B4A', lw=2, label='Infected')
  ax2.plot(days, history['r'], color='#639922', lw=2, label='Recovered')
  ax2.set_xlabel("Day")
  ax2.set_ylabel("Agents")
  ax2.set_title("SIR curve", fontweight='bold')
  ax2.legend()

  plt.tight_layout()
  plt.savefig("evolution.png", dpi=150)
  plt.show()